#we use def keyword to define a function
#functions can take what we call arguments or parameters, which are values we can pass into the function to customize its behavior.
#we pass name as an argument to the greet function. When we call the function, we provide a specific value for name, and the function uses that value to generate a personalized greeting.
def greet(name):
    print(f"Hello, {name}! Welcome to the Python course.")

#calling the function
greet("Alice")  # Output: Hello, Alice! Welcome to the Python course.
